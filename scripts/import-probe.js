/* Generates a temporary entry file that imports EVERY module under src/, so
   `bundle:check` actually exercises them.
 *
   Without this, Metro only bundles what the current screens happen to reach.
   A component written in one phase but not wired up until three phases later
   would sit unverified the whole time — a bad import path or a missing native
   package would only surface much later, far from the change that caused it. */
const fs = require('fs');
const path = require('path');

const SKIP = /(^|\/)(assets)\//;
const files = [];
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => {
  const f = path.join(d, e.name);
  if (e.isDirectory()) return walk(f);
  if (!/\.(js|jsx)$/.test(e.name)) return;
  if (SKIP.test(f)) return;
  files.push(f);
});
walk('src');
files.sort();

const lines = files.map((f, i) => {
  const spec = '@/' + f.replace(/^src\//, '').replace(/\.(js|jsx)$/, '');
  return `import * as m${i} from '${spec}';`;
});

const out = `/* GENERATED by scripts/import-probe.js — do not edit or commit. */
import './global.css';
${lines.join('\n')}

const ALL = [${files.map((_, i) => `m${i}`).join(', ')}];

export default function Probe() {
  return ALL.length;
}
`;
fs.writeFileSync('.import-probe.jsx', out);
fs.writeFileSync('.import-probe-entry.js', "import Probe from './.import-probe';\nglobal.__probe = Probe;\n");
console.log(`import probe covers ${files.length} modules`);
